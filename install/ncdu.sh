#!/usr/bin/env bash

# DU with NCurses interface

# ncdu (NCurses Disk Usage) is a disk utility for Unix systems. Its name refers
# to its similar purpose to the du utility, but ncdu uses a text-based user
# interface under the [n]curses programming library.[2] Users can navigate the
# list using the arrow keys and delete files that are taking up too much space
# by pressing the 'd' key.

sudo pacman -S ncdu
